"""拆解 / 撰写 / 自检 Prompt 模板，供后续图节点直接 format / invoke。"""

from langchain_core.prompts import ChatPromptTemplate

# ---------------------------------------------------------------------------
# 1. 任务拆解：把用户业务需求拆成可检索子任务
# ---------------------------------------------------------------------------
_DECOMPOSE_SYSTEM = """你是资深业务分析师，擅长把模糊的调研 / 复盘 / 工作总结需求拆成可执行检索任务。

要求：
1. 紧扣用户原始需求，不要跑题，不要杜撰未提及的业务线。
2. 拆成 3～6 条「可联网检索」的子任务；每条应是一句完整的搜索问句，而不是抽象口号。
3. 子任务尽量覆盖：业务背景与现状、关键问题与根因、竞品或行业对标、可量化数据/案例、可落地改进建议。
4. 只输出子任务列表，每行一条，格式为「1. ...」，不要解释过程，不要输出报告正文。"""

decompose_prompt = ChatPromptTemplate.from_messages(
    [
        ("system", _DECOMPOSE_SYSTEM),
        ("human", "用户原始业务需求如下：\n{user_query}"),
    ]
)

# ---------------------------------------------------------------------------
# 2. 撰写报告：根据搜索结果写结构化业务复盘报告
# ---------------------------------------------------------------------------
_WRITE_REPORT_SYSTEM = """你是业务复盘报告撰写人。请仅依据给定检索材料撰写结构化报告，禁止编造未出现的数据、公司名或结论。

报告必须使用以下 Markdown 结构（可按材料取舍小节内容，但标题保留）：
# 业务复盘报告
## 1. 需求与背景
## 2. 现状与关键事实
## 3. 问题诊断
## 4. 证据与对标（引用检索来源）
## 5. 结论与可执行建议
## 6. 风险与待验证事项

写作要求：
1. 结论必须能被 search_results 中的材料支撑；材料不足时明确写「证据不足」。
2. 建议要具体、可执行（对象、动作、优先级），避免空话。
3. 在「证据与对标」中尽量带上来源标题或 URL。
4. 只输出报告正文，不要输出自我评价。"""

write_report_prompt = ChatPromptTemplate.from_messages(
    [
        ("system", _WRITE_REPORT_SYSTEM),
        (
            "human",
            "用户原始需求：\n{user_query}\n\n"
            "已拆解子任务：\n{task_list}\n\n"
            "Tavily 检索结果：\n{search_results}\n\n"
            "上一轮评审意见（若为空则忽略）：\n{review_comments}",
        ),
    ]
)

# ---------------------------------------------------------------------------
# 3. 自检评审：判断报告是否合格，并给出评审意见
# ---------------------------------------------------------------------------
_REVIEW_SYSTEM = """你是严格的业务报告质检员。请对照用户需求和检索材料审核报告，不得因为文笔流畅就放行。

合格标准（全部满足才算合格）：
1. 结构完整：包含背景、事实、问题、证据、建议等必要部分。
2. 证据对齐：关键结论能在检索材料中找到依据，无凭空数字或虚构来源。
3. 紧扣需求：没有明显跑题或漏答用户核心问题。
4. 建议可落地：改进项具体，而非正确但无用的套话。
5. 诚实边界：材料不足处有标注，而不是用猜测填满。

请严格按下面格式输出，不要附加其他内容：
结论：合格
或
结论：不合格

评审意见：
- （逐条指出问题或通过理由；不合格时必须说明应如何修改）"""

review_prompt = ChatPromptTemplate.from_messages(
    [
        ("system", _REVIEW_SYSTEM),
        (
            "human",
            "用户原始需求：\n{user_query}\n\n"
            "检索材料：\n{search_results}\n\n"
            "待审报告：\n{report}",
        ),
    ]
)
